"""`make pbi-guide`: docs/powerbi_build_guide.md, a click-by-click guide for building 3 report pages on the
PBIP model, with the numbers each visual should show (filled from outputs/kpis.json, so they cannot drift).
The visuals are built by hand in Power BI Desktop; no visual JSON is authored blind."""

from __future__ import annotations

import json

from sifpa.paths import DOCS, OUTPUTS


def main() -> None:
    k = json.loads((OUTPUTS / "kpis.json").read_text())
    v = json.loads((OUTPUTS / "variance_pack_SYNTHETIC.json").read_text())
    mk = json.loads((OUTPUTS / "market.json").read_text())
    s1 = next(r for r in v["by_site_ytd"] if r["site_id"] == "S1")
    usd = lambda x: f"${x:,.0f}"  # noqa: E731
    pct = lambda x: f"{x * 100:.1f}%"  # noqa: E731
    top = mk["market_top10"][0]
    text = f"""# Power BI build guide (30-45 minutes)

This repo ships the semantic model as text (PBIP + TMDL). It was authored on a Mac, so **it has never been
opened in Power BI Desktop**. This guide builds the three report pages by hand. Each step lists the number
the visual should show, so you can see at once whether the model and its DAX work. The numbers come from the
SQL twins (`outputs/kpis.json`), generated by `make pbi-guide`.

## 0. Open and refresh (5 min)
1. On Windows, clone the repo, e.g. to `C:\\repos\\specialty-infusion-fpa`.
2. Open `powerbi/SpecialtyInfusionFPA.pbip` in Power BI Desktop. Ignore the warning about empty pages.
3. **Transform data > Manage parameters > RepoPath**: set it to the clone folder, then **Close & Apply**.
4. **Model view** should show 23 tables and 21 relationships. Check that `fact_plan_month`,
   `fact_actual_month_SYNTHETIC` and `fact_fixed_month` all join to `dim_site`, `dim_date[date]` and
   `dim_item` (and `dim_item` to `dim_drug`).
5. Mark `dim_date` as the date table if Desktop has not already (Table tools > Mark as date table > `date`).

## Page 1: Budget vs actual (SYNTHETIC actuals) (15 min)
- **Slicers** (one row at the top): `dim_site[site_name]`, `dim_date[month_name]`, `dim_item[payer]`.
- **Cards**, with the site slicer = Site A and no month selected:
  - `Budget Contribution` = **{usd(k["budget_contribution"])}** (full year)
  - `Budget Operating Margin` = **{usd(k["budget_operating_margin"])}**
  - `Actual Contribution (SYNTHETIC)` = **{usd(k["actual_contribution_synthetic"])}** (Jan-Mar)
  - `Contribution Variance (SYNTHETIC)` = **{usd(k["contribution_variance_synthetic"])}**
- **Waterfall: budget to actual.** Power BI has no built-in bridge, so build it from a small step table:
  1. **Modeling > New table**, then paste:
     ```DAX
     Bridge Step = DATATABLE ( "Step", STRING, "Order", INTEGER,
         {{ {{ "Budget to date", 1 }}, {{ "Volume", 2 }}, {{ "Mix", 3 }}, {{ "Rate", 4 }} }} )
     ```
     Select `Bridge Step[Step]`, then **Column tools > Sort by column > Order**. Do not relate this table
     to anything.
  2. **New measure** on `Bridge Step`:
     ```DAX
     Bridge Value =
     SWITCH ( SELECTEDVALUE ( 'Bridge Step'[Step] ),
         "Budget to date", [Budget Contribution to Date],
         "Volume", [Volume Variance (SYNTHETIC)],
         "Mix", [Mix Variance (SYNTHETIC)],
         "Rate", [Rate Variance (SYNTHETIC)] )
     ```
  3. Insert a **Waterfall** with Category = `Bridge Step[Step]` and Y-axis = `[Bridge Value]`. Leave
     "Show total" on: the total bar is the actual.
  4. Expected values for Site A: Budget to date **{usd(k["budget_contribution_to_date"])}**, Volume
     **{usd(k["volume_variance_synthetic"])}**, Mix **{usd(k["mix_variance_synthetic"])}**, Rate
     **{usd(k["rate_variance_synthetic"])}**. The total should equal `Actual Contribution (SYNTHETIC)`
     **{usd(k["actual_contribution_synthetic"])}**. The three variances sum to
     {usd(s1["variance"])}.
- **Clustered column**: X = `dim_date[month_name]`, values = `Budget Contribution` and
  `Actual Contribution (SYNTHETIC)`. Actuals exist for Jan-Mar only.
- **Check slicing**: set payer = commercial. `Budget Contribution per Admin` should read
  **{usd(k["budget_contribution_per_admin"])}** for Site A.
- Title the page "Budget vs actual - SYNTHETIC actuals (method demo)".

## Page 2: Margin and pricing (10 min)
- **Table** on `fact_margin_per_admin`: `hcpcs`, `molecule`, `contribution_medicare_ffs`,
  `contribution_commercial`, `mix_share`. Sort by `mix_share` descending.
- **Cards**:
  - `Median Lag Spread %` = **{pct(k["median_lag_spread_pct"])}**
  - `Underwater Share After Sequestration and Coinsurance` = **{pct(k["underwater_share_after_sequestration_and_coinsurance"])}**
- **Line chart**: X = `fact_asp_quarter[quarter_start]`, Y = `payment_limit` (average), legend =
  `dim_drug[brand]`, filtered to `dim_drug[molecule]` = infliximab.
- **Card** `Biosimilar Share of Administrations`, with filters molecule = infliximab and
  `fact_national_drug_year[year]` = 2024: **{pct(k["biosimilar_share_of_administrations"])}**.

## Page 3: Growth and benchmark (10 min)
- **Table** on `dim_market`, filtered to `eligible` = True and `rank` <= 10: `rank`, `market_name`,
  `share_of_weightings_in_top10`, `specialists_per_100k`, `infusion_billers_per_100k`, `hospital_heavy`.
  Row 1 should be **{top["market"]}**.
- **Cards**:
  - `Eligible Markets` = **{int(k["eligible_markets"])}**
  - `Share of Weightings in Top 10`, with a single-market filter on Canton-Massillon, OH = **{pct(k["share_of_weightings_in_top_10"])}**
- **Table** on `fact_provider_scorecard` with a slicer on `provider_type`. With provider_type =
  Rheumatology, `Median Allowed per Beneficiary` = **{usd(k["median_allowed_per_beneficiary"])}**.
- **Card** `Scenario Contribution`, with a slicer on `fact_scenarios[scenario]`. policy_2028 =
  **{usd(k["scenario_contribution"])}**.

## If a number does not match
The SQL twin of every measure is in `sql/measures/<measure>.sql`, and the first comment line states the
filter context it was evaluated in. A mismatch means one of three things: a relationship is wrong, a filter
context differs from the one stated, or the DAX has a bug (it has never been executed). Fix the DAX in
`src/sifpa/pbi_measures.py` and rerun `make pbi kpis pbi-guide`.
"""
    (DOCS / "powerbi_build_guide.md").write_text(text)
    print("docs/powerbi_build_guide.md written")


if __name__ == "__main__":
    main()
